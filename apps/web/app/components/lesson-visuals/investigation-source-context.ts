export function withInvestigationSourceContexts(
  registry: Readonly<Record<string, LessonInvestigationSpec>>,
): Record<string, LessonInvestigationSpec> {
  return Object.fromEntries(
    Object.entries(registry).map(([slug, spec]) => {
      const context = INVESTIGATION_SOURCE_CONTEXTS[slug];
      if (!context || spec.source) return [slug, spec];
      return [
        slug,
        {
          ...spec,
          source: {
            ...context,
            caseScopes: Object.fromEntries(
              spec.cases.map((selected) => [selected.id, selected.description]),
            ),
          },
        },
      ];
    }),
  );
}

export function selectedInvestigationSource(
  source: InvestigationSourceContext,
  caseId: string,
): InvestigationSourceContext {
  return { ...source, scope: source.caseScopes?.[caseId] ?? source.scope };
}
